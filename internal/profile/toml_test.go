func requireTOMLEqual[T any](t *testing.T, name string, expected T, actual T) {
	t.Helper()

	if diff := cmp.Diff(expected, actual); diff != "" {
		t.Fatalf("%s mismatch (-expected +actual):\n%s", name, diff)
	}
}

func requireConfigEqual(t *testing.T, expected Profile, actual Profile) {
	t.Helper()

	if diff := cmp.Diff(expected, actual, cmpopts.EquateEmpty()); diff != "" {
		t.Fatalf("config mismatch (-expected +actual):\n%s", diff)
	}
}

func TestDecodeReadsMultilineArrays(t *testing.T) {
	t.Parallel()

	config, err := decodeTOML(`schema_version = 1

[path_roles]
go_source = [
	"cmd/",
	"internal/",
]
`)
	if err != nil {
		t.Fatalf("Decode: %v", err)
	}

	requireTOMLEqual(t, "path_roles", PathRoles{
		"go_source": {"cmd/", "internal/"},
	}, config.PathRoles)
}

func TestDecodeReadsTargetWorkingDirectory(t *testing.T) {
	t.Parallel()

	config, err := decodeTOML(`schema_version = 1

[targets.tools_go]
language = "go"
scope = "tools"
working_directory = "tools"
`)
	if err != nil {
		t.Fatalf("Decode: %v", err)
	}

	target, found := config.Targets.Lookup("tools_go")
	if !found {
		t.Fatal("expected tools_go target")
	}

	if target.WorkingDirectory != "tools" {
		t.Fatalf("working dir = %q", target.WorkingDirectory)
	}
}

